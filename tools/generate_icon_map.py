#!/usr/bin/env python3
"""Writes scripts/ecoIcons.js: the menu icon for every eco: item, taken from the
resource pack's item_texture.json (so menus use exactly the inventory icon)."""
import glob, json, os
ROOT = os.path.join(os.path.dirname(__file__), "..", "packs")
tex = json.load(open(os.path.join(ROOT, "SkyblockEconomy_RP", "textures", "item_texture.json")))["texture_data"]
icons = {}
for f in glob.glob(os.path.join(ROOT, "SkyblockEconomy_BP", "items", "**", "*.json"), recursive=True):
    d = json.load(open(f))["minecraft:item"]
    key = d["components"].get("minecraft:icon")
    if isinstance(key, dict):
        key = key.get("textures", {}).get("default") or key.get("texture")
    t = tex.get(key, {}).get("textures")
    if isinstance(t, list):
        t = t[0]
    if t:
        icons[d["description"]["identifier"]] = t
out = "// AUTO-GENERATED by tools/generate_icon_map.py from textures/item_texture.json - don't edit by hand.\n"
out += "// Menu icon for every eco: item (the same texture as its inventory icon).\n"
out += "export const ECO_ICONS = " + json.dumps(dict(sorted(icons.items())), indent=2) + ";\n"
open(os.path.join(ROOT, "SkyblockEconomy_BP", "scripts", "ecoIcons.js"), "w").write(out)
print(len(icons), "icons")
